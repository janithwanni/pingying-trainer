// Programmatic numbers 0–100
const digits = ["零", "一", "二", "三", "四", "五", "六", "七", "八", "九"];
const dpy = ["líng", "yī", "èr", "sān", "sì", "wǔ", "liù", "qī", "bā", "jiǔ"];
const dplain = ["ling2", "yi1", "er4", "san1", "si4", "wu3", "liu4", "qi1", "ba1", "jiu3"];

function numberWord(n) {
  if (n < 10) return [digits[n], dpy[n], dplain[n]];
  if (n === 10) return ["十", "shí", "shi2"];
  if (n < 20) return ["十" + digits[n - 10], "shí" + dpy[n - 10], "shi2" + dplain[n - 10]];
  const t = Math.floor(n / 10);
  if (n % 10 === 0) return [digits[t] + "十", dpy[t] + "shí", dplain[t] + "shi2"];
  return [
    digits[t] + "十" + digits[n % 10],
    dpy[t] + "shí" + dpy[n % 10],
    dplain[t] + "shi2" + dplain[n % 10],
  ];
}

const numbers = [];
for (let n = 0; n <= 100; n++) {
  if (n === 100) {
    numbers.push(["一百", "yìbǎi", "yi4bai3", "100", "Numbers"]);
    continue;
  }
  const [hz, py, pl] = numberWord(n);
  numbers.push([hz, py, pl, String(n), "Numbers"]);
}

export const VOCAB = manual.concat(numbers).map((row, i) => ({
  hz: row[0],
  py: row[1],
  plain: row[2],
  en: row[3],
  cat: row[4],
  id: i,
  key: "w:" + row[0],
}));

export const VOCAB_BY_HZ = new Map(VOCAB.map((v) => [v.hz, v]));

export const CATEGORIES = Array.from(new Set(VOCAB.map((v) => v.cat)));
